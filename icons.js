function iconSVG(name) {
  const rows = ICONS[name];
  const h = rows.length, w = rows[0].length, size = Math.max(w, h);
  const ox = (size - w) / 2, oy = (size - h) / 2;
  let rects = "";
  rows.forEach((row, y) => {
    for (let x = 0; x < w; x++)
      if (row[x] === "#") rects += `<rect x="${x + ox}" y="${y + oy}" width="1.02" height="1.02"/>`;
  });
  return `<svg viewBox="0 0 ${size} ${size}" fill="#fff" aria-hidden="true">${rects}</svg>`;
}

function fillIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach(el => { el.innerHTML = iconSVG(el.dataset.icon); });
}
